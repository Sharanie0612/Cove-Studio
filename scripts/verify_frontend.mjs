assert.equal(translated.ui.fields[0].options[0].label,'Translated');assert.equal(translated.ui.fields[0].options[0].value,'Base');
assert.equal(translated.ui.fields[0].default,'Base');assert.equal(translated.commands[0],'Base');assert.equal(translated.ui.actions[0].command,'Base');
assert.equal(translated.ui.result.table.columns[0].label,'Translated');assert.equal(translated.ui.result.table.columns[0].key,'Base');assert.equal(translated.ui.result.table.columns[0].unit,'Base');
assert.equal(JSON.stringify(localizedSource),original);setLocale('zh-CN');assert.equal(localizeTool(localizedSource).name,'Base');assert.equal(localizeTool(translated).name,'Base');
console.log('Plugin catalogs preserve identifiers, defaults, option values, units and original metadata.');
