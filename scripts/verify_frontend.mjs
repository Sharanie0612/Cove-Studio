import assert from 'node:assert/strict';
import { initialWorkbench, workbenchReducer as reduce } from '../src/core/workbench.ts';
import { fieldDefaults } from '../src/core/fields.ts';
import { filterTools, surfaceKind, toolStatus, localizeTool } from '../src/core/pluginPresentation.ts';
import { contrast, customFromScheme, normalizeAppearance, resolvedMode, themeTokens } from '../src/core/appearance.ts';
const a = { id: 'tool.a', enabled: true }, b = { id: 'tool.b', enabled: true }, c = { id: 'tool.c', enabled: true };
let state = [a,b,c].reduce((next, tool) => reduce(next, { type: 'open', tool }), initialWorkbench);
assert.equal(state.activeId, c.id);
state = reduce(state, { type: 'activate', id: b.id });
state = reduce(state, { type: 'close', id: b.id });
assert.equal(state.activeId, c.id, 'closing the current tab must select its neighbour');
assert.equal(state.view, 'tool');
state = reduce(state, { type: 'view', view: 'guide' });
state = reduce(state, { type: 'close', id: c.id });
assert.equal(state.view, 'guide', 'closing a tab while reading must preserve the guide');
assert.equal(state.activeId, a.id);
state = reduce(state, { type: 'restart', id: a.id });
assert.equal(state.tabs.length, 1, 'restart must keep the tab');
assert.equal(state.epochs[a.id], 1);
state = reduce(state, { type: 'reconcile', tools: [{ ...a, enabled: false }] });
assert.equal(state.tabs.length, 0, 'disabled or removed tools must not leave stale tabs');
assert.equal(fieldDefaults([{ id:'mode', type:'select', options:[{value:'text',label:'Text'}] }]).mode, 'text');
assert.equal(fieldDefaults([{ id:'port', type:'number', default:0 }]).port, 0);
const migrated = normalizeAppearance(null, 'dark');
assert.equal(migrated.mode, 'dark', 'upgrades must retain the previous appearance mode');
assert.equal(migrated.scheme, 'cove');
assert.equal(normalizeAppearance({scheme:'vscode',mode:'dark'}).scheme, 'vscode', 'a saved preset must survive the new default');
assert.equal(resolvedMode('system', true), 'dark');
assert.equal(resolvedMode('system', false), 'light');
assert.equal(resolvedMode('light', true), 'light');
const invalid = normalizeAppearance({ scheme:'missing', mode:'broken', custom:{ light:{ accent:'url(https://invalid.example)', background:'#ABCDEF' } } });
assert.equal(invalid.scheme, 'cove');
assert.equal(invalid.mode, 'light');
assert.equal(invalid.custom.light.background, '#abcdef');
assert.equal(invalid.custom.light.accent, customFromScheme('cove').light.accent, 'invalid persisted CSS values must never reach the page');
const custom = customFromScheme('github');
custom.light.accent = '#8957e5';
const saved = normalizeAppearance(JSON.parse(JSON.stringify({ mode:'system', scheme:'custom', custom })));
assert.equal(themeTokens(saved,'light').blue, '#8957e5');
assert.equal(themeTokens(saved,'dark').blue, customFromScheme('github').dark.accent, 'editing light colors must preserve the dark scheme');
assert.equal(customFromScheme('github').light.accent, '#0969da', 'custom editing must not mutate the presets');
for (const scheme of ['vscode','github','paper','cove']) for (const mode of ['light','dark']) {
  const tokens = themeTokens(normalizeAppearance({scheme}),mode);
  assert.ok(contrast(tokens.text,tokens.bg) >= 7, `${scheme} ${mode} needs readable page text`);
  assert.ok(contrast(tokens['on-primary'],tokens.primary) >= 4.3, `${scheme} ${mode} needs readable button labels`);
  assert.equal(tokens['terminal-bg'],tokens.bg, 'terminal and app surfaces must use the same palette');
  assert.ok(contrast(tokens['terminal-black'],tokens['terminal-bg']) >= 4.5, 'ANSI black output must stay visible in light and dark terminals');
}
const git = themeTokens(normalizeAppearance({scheme:'github'}),'light');
assert.notEqual(git.primary,git.blue, 'GitHub primary actions and link accents must remain separate');
console.log('Frontend state and appearance regression checks passed.');
const terminal = { id:'test.terminal',name:'Terminal fixture',description:'In-memory terminal',category:'Network',ui:{surface:'terminal'},runtime:{connected:true} };
const job = { id:'dev.export',name:'Exporter',description:'Build outputs',category:'Files',ui:{surface:'form',job:{}} };
const fixtures = [terminal,job];
assert.deepEqual(filterTools(fixtures,'EXPORT','Files',[],false),[job]);
assert.deepEqual(filterTools(fixtures,'','',['dev.export'],true),[job]);
assert.equal(filterTools(fixtures,'','',['dev.export'],false)[0].id,'dev.export');
assert.equal(fixtures[0],terminal,'filtering must not reorder the catalog');
assert.equal(surfaceKind(terminal),'terminal');
assert.equal(surfaceKind(job),'job');
assert.equal(surfaceKind({...job,ui:{surface:'web',web:{}}}),'web');
assert.equal(surfaceKind({...job,ui:{surface:'form'}}),'form');
assert.equal(toolStatus(terminal),'已连接');
assert.equal(toolStatus({...terminal,compatibilityStatus:{supported:false,reasons:['version']}}),'需要兼容版本');
const mounted = reduce(initialWorkbench,{type:'open',tool:terminal});
assert.equal(reduce(mounted,{type:'view',view:'ai-tools'}).tabs,mounted.tabs,'navigation must retain mounted tab identities');
const lateOpen = reduce(initialWorkbench,{type:'open',tool:terminal,activate:false});
assert.equal(lateOpen.view,'home','a slow open must not override newer navigation');
assert.equal(lateOpen.tabs.length,1,'a background open retains its mounted workspace');
console.log('Workbench search, favorites, surface selection and compatibility checks passed.');

